import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
import {transformSync} from 'esbuild';
import assert from 'node:assert/strict';
const html=readFileSync(new URL('../public/companion.html',import.meta.url),'utf8');
const js=html.split('<script type="module">')[1]?.split('</script>')[0];
assert.ok(js,'companion module exists');
transformSync(js,{sourcefile:'public/companion.html',loader:'js',format:'esm',target:'es2022'});
for(const name of ['feed','clean','pet','sleep'])assert.ok(html.includes('data-action="'+name+'"'),'missing '+name);
assert.ok(js.includes('api(\'action\''),'actions use server API');
assert.ok(js.includes('ctx.drawImage(img,x,y,w,h'),'atlas source crop is explicit');
assert.ok(js.includes("detailedArt[key]"),'pet art comes from the game atlas manifest');
assert.ok(html.includes('companion.webmanifest'),'install manifest is linked');
const manifest=JSON.parse(readFileSync(new URL('../public/companion.webmanifest',import.meta.url),'utf8'));
assert.equal(manifest.start_url,'/companion.html');
const serviceWorker=readFileSync(new URL('../public/companion-sw.js',import.meta.url),'utf8');
new Script(serviceWorker,{filename:'public/companion-sw.js'});
assert.ok(serviceWorker.includes('showNotification'),'push handler shows visible notifications');
assert.ok(js.includes("api('push-subscribe'"),'PWA subscribes to server push');
assert.ok(js.includes('navigator.serviceWorker.register'),'PWA registers service worker');
assert.ok(js.includes("Notification.requestPermission"),'permission requires explicit user action');
assert.ok(html.includes('id="installDirections"'),'browser-only iPhone install instructions exist');
const pushInitializer=js.slice(js.indexOf('async function registerPush(){'),js.indexOf("$('enablePush').onclick"));
assert.ok(pushInitializer.indexOf("if(!installed())")<pushInitializer.indexOf("if(!('serviceWorker'"),'install check comes before browser push support check');
assert.ok(manifest.icons?.[0]?.src==='/companion-icon.png','iOS web app icon');
console.log('Companion page: syntax, offline shell and push hook checks passed');
